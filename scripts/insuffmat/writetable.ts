// scripts/insuffmat/writetable.ts

/**
 * Writes the site's src/shared/chess/logic/insuffmat/matingsets.ts from the generator's output:
 * every smallest mating set of both tables, ranked by the site's own
 * insufficientmaterial.getCanonicalRank, so the table and its lookup can never disagree. Each
 * table's cap is the highest level generated.
 *
 * Usage: npx tsx scripts/insuffmat/writetable.ts <out dir of generate.ts>
 */

import fs from 'node:fs';

import insufficientmaterial from '../../src/shared/chess/logic/insuffmat/insufficientmaterial.js';

import matesearch from './matesearch.js';

// Constants -------------------------------------------------------------------

const TABLE_FILE = 'src/shared/chess/logic/insuffmat/matingsets.ts';

// Table -----------------------------------------------------------------------

/** One table's smallest mating sets as sorted canonical ranks, and its cap. */
function readTable(dir: string): { ranks: number[]; cap: number } {
	const files = fs.readdirSync(dir).filter((file) => /^mates-\d+\.tsv$/.test(file));
	const cap = Math.max(...files.map((file) => Number(file.match(/\d+/)![0])));
	const ranks = new Set<number>();
	for (const file of files)
		for (const line of fs.readFileSync(`${dir}/${file}`, 'utf8').split('\n').filter(Boolean)) {
			const label = line.split('\t')[0]!;
			const [white, black] = matesearch.parse(label.split(' @')[0]!);
			const material = new Map<string, number>();
			for (const [kind, count] of Object.entries(white)) material.set(kind, count);
			for (const [kind, count] of Object.entries(black))
				material.set(kind.toLowerCase(), count);
			const rank = insufficientmaterial.getCanonicalRank(material);
			if (rank === -1) throw Error(`A piece in "${label}" is missing from insufficientmaterial's RANKED_CODES`); // prettier-ignore
			ranks.add(rank);
		}
	return { ranks: [...ranks].sort((a, b) => a - b), cap };
}

/** Sorted ranks as insufficientmaterial decodes them: the gaps between them, in base-32 RANK_DIGITS. */
function encodeRanks(ranks: number[]): string {
	const digits = insufficientmaterial.RANK_DIGITS;
	return ranks
		.map((rank, i) => {
			let gap = rank - (ranks[i - 1] ?? 0);
			let text = digits[gap % 32]!;
			while ((gap = Math.floor(gap / 32)) > 0) text = digits[32 + (gap % 32)]! + text;
			return text;
		})
		.join('');
}

// Entry -----------------------------------------------------------------------

const outDir = process.argv[2];
if (outDir === undefined)
	throw Error('Usage: npx tsx scripts/insuffmat/writetable.ts <out dir of generate.ts>');
const unbounded = readTable(`${outDir}/unbounded`);
const bounded = readTable(`${outDir}/bounded`);
fs.writeFileSync(
	TABLE_FILE,
	`// ${TABLE_FILE}

/**
 * GENERATED by scripts/insuffmat/writetable.ts, do not edit. Every smallest piece set that can be
 * arranged into a checkmate, per board kind, up to each cap, by insufficientmaterial's canonical
 * rank, as its decodeRanks reads them. Terms, evidence and known holes: scripts/insuffmat/README.md.
 */

export default {
	cap: { unbounded: ${unbounded.cap}, bounded: ${bounded.cap} },
	unbounded:
		'${encodeRanks(unbounded.ranks)}',
	bounded:
		'${encodeRanks(bounded.ranks)}',
};
`,
);
console.log(
	`wrote ${unbounded.ranks.length} unbounded (cap ${unbounded.cap}) and ${bounded.ranks.length} bounded (cap ${bounded.cap}) mating sets`,
);
